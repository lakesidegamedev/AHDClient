fn main() {
  // Android: align the native library for 16 KB memory pages. NDK r27 links
  // at 4 KB, which devices running a 16 KB page kernel (newer Pixels on
  // Android 16+) cannot load, so the app died on launch (ticket 1387). Set
  // here rather than in .cargo/config.toml so a RUSTFLAGS override from the
  // Tauri CLI cannot drop it.
  if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("android") {
    println!("cargo:rustc-link-arg=-Wl,-z,max-page-size=16384");
    println!("cargo:rustc-link-arg=-Wl,-z,common-page-size=16384");
  }
  // App-defined commands (not plugin commands): their permission identifiers
  // are autogenerated here and referenced bare from capabilities/default.json.
  // Only the "main" (launcher) window may invoke them. The "online" and
  // "game" windows get zero IPC surface; see capabilities/online.json and
  // capabilities/game.json. Mobile builds register only the subset listed in
  // capabilities/mobile.json.
  tauri_build::try_build(
    tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(&[
      "get_push_status", "configure_push", "send_test_push", "get_briefing",
      "open_briefing_page",
      "open_game_page",
      "open_briefing_window",
      "set_briefing_pinned",
      "set_statistics_consent",
      "submit_statistics",
      "submit_diagnostics",
      "linked_account",
      "sign_out",
      "link_account",
      "close_embedded_game",
      "set_embedded_visible",
      "refresh_game_view",
      "open_online_window",
      "open_help_destination",
      "open_ask_window",
      "ask_api",
      "ask_send",
      "ask_stop",
      "open_game_window",
      "game_start",
      "game_stop",
      "game_status",
      "game_request",
      "list_worlds",
      "create_world",
      "touch_world",
      "delete_world",
      "list_game_versions",
      "install_game_version",
      "select_game_version",
    ])),
  )
  .expect("failed to run tauri-build");
}
